/// An infinite, seeded tile world that follows the camera.
///
/// ```dart
/// world.add(
///   ProceduralMap(
///     seed: 42,
///     generator: WorldGenerator(...),
///     tileset: Tileset(...),
///   ),
/// );
/// ```
///
/// Chunks are generated around the camera's visible area as it moves and
/// unloaded when they're far away. Generation runs on a worker isolate, or
/// on the web within a time budget per frame, so new chunks appear a few
/// frames after they come into range. Tile (0, 0) is drawn at the map's
/// origin, and each tile is [Tileset.tileSize] pixels.
///
/// Turn on [debugMode] to see chunk borders, chunk coordinates and scatter
/// spots.
class ProceduralMap extends Component with HasGameReference<FlameGame> {
  /// Creates a map of the world with [seed], generated by [generator] and
  /// drawn with [tileset].
  ///
  /// [chunkSize] is the number of tiles along each side of a chunk and must
  /// be a power of two. [camera] defaults to the game's camera.
  ///
  /// With [collision], solid tiles get hitboxes, see [SolidTiles]. Your game
  /// or world needs Flame's [HasCollisionDetection] mixin.
  ///
  /// The generator is sent to a worker isolate, so it must not reference
  /// anything that can't cross isolates, such as images or components. Only
  /// [Scatter.spawn] may, because it runs on the main isolate.
  ///
  /// If you sort objects by [priority], give the map a lower one, so it's
  /// drawn below them.
  ///
  /// Pass saved [edits] to restore the changes a game made to this world.
  /// Throws if they use a tile type that isn't in the tileset or any biome.
  ProceduralMap({
    required this.seed,
    required this.generator,
    required this.tileset,
    int chunkSize = 32,
    StreamingOptions? streaming,
    this.collision = false,
    WorldEdits? edits,
    this.onChunkLoaded,
    this.onChunkUnloaded,
    CameraComponent? camera,
    super.priority,
  }) : grid = ChunkGrid(chunkSize),
       streaming = streaming ??= StreamingOptions(),
       _camera = camera,
       _palette = ChunkGenerator.paletteFor(generator, tileset.tiles.keys),
       _chunkPixels = tileset.tileSize * chunkSize.toDouble(),
       _cache = ChunkCache(streaming.cacheSize),
       edits = edits ?? WorldEdits() {
    for (final MapEntry(key: coord, value: name) in this.edits.tiles.entries) {
      final type = _palette.byName(name);
      if (type == null) {
        throw ArgumentError.value(
          name,
          'edits',
          'changes tile (${coord.x}, ${coord.y}) to a tile type that is not in '
              'the tileset or any biome',
        );
      }
      _editTile(coord, _palette.idOf(type));
    }
  }

  /// The world seed.
  final int seed;

  /// Decides which tile type goes where.
  final WorldGenerator generator;

  /// Decides how each tile type is drawn.
  final Tileset tileset;

  /// The size of the chunks.
  final ChunkGrid grid;

  /// How chunks are loaded and unloaded.
  final StreamingOptions streaming;

  /// Whether solid tiles get hitboxes. Each loaded chunk adds a [SolidTiles]
  /// child for every solid tile type in it.
  final bool collision;

  /// The changes made with [setTile].
  final WorldEdits edits;

  /// Called when a chunk is loaded, during [update] and before the chunk is
  /// first rendered.
  final void Function(Chunk chunk)? onChunkLoaded;

  /// Called when a chunk is unloaded, during [update] or when the map is
  /// removed.
  final void Function(Chunk chunk)? onChunkUnloaded;

  final CameraComponent? _camera;
  final TilePalette _palette;

  /// Whether each tile id is solid.
  late final List<bool> _solid = [
    for (final type in _palette.types) type.solid,
  ];
  late final TileSources _sources;
  late final ChunkPainter _painter;
  final _loaded = <ChunkCoord, _LoadedChunk>{};

  /// The tile ids of [edits], by chunk and then by local index.
  final _editedTiles = <ChunkCoord, Map<int, int>>{};

  /// Loaded chunks whose sprites are out of date after [setTile].
  final _repaint = <ChunkCoord>{};

  /// Loaded chunks whose hitboxes are out of date after [setTile].
  final _rebuildSolids = <ChunkCoord>{};

  /// Chunks that aren't loaded, from the streamer and from queries.
  final ChunkCache _cache;

  /// Generates chunks for queries outside the loaded area, and evaluates
  /// fields for [valueAt].
  late final _queries = ChunkGenerator(
    generator,
    seed: seed,
    grid: grid,
    tiles: tileset.tiles.keys,
  );
  final _paint = Paint()..filterQuality = FilterQuality.none;

  /// Seconds since the map started, the clock of every tile animation.
  var _time = 0.0;

  /// The frame each animated tile id shows, indexed by tile id.
  late final List<int> _frames;

  /// Loads and unloads chunks. Null while the worker is starting and after
  /// the map is removed.
  ChunkStreamer? _streamer;
  Future<void>? _starting;

  /// Whether the map is loading or mounted, so a worker that finishes
  /// starting after the map is removed is stopped again.
  var _active = false;

  CameraComponent get _activeCamera => _camera ?? game.camera;

  /// Returns the tile under [position], in the map's coordinates.
  ///
  /// Works anywhere, even before the map is added to the game. If the tile's
  /// chunk isn't loaded, it's generated on the spot, which takes a
  /// millisecond or two, and kept in the cache so it's not generated twice.
  TileType tileAt(Vector2 position) => tileAtCoord(tileCoordAt(position));

  /// Returns the tile at [coord]. See [tileAt].
  TileType tileAtCoord(TileCoord coord) {
    final chunk = grid.chunkOf(coord);
    // Loaded chunks already have their edits.
    final id = _loaded.containsKey(chunk)
        ? null
        : _editedTiles[chunk]?[grid.localIndex(coord)];
    return _palette[id ?? _chunkData(coord).tileIdAt(coord)];
  }

  /// Returns the biome under [position], in the map's coordinates. See
  /// [tileAt].
  Biome biomeAt(Vector2 position) => biomeAtCoord(tileCoordAt(position));

  /// Returns the biome at [coord]. See [tileAt].
  Biome biomeAtCoord(TileCoord coord) =>
      generator.biomes[_chunkData(coord).biomeAt(coord)];

  /// Returns the value of [field] at [position], in the map's coordinates,
  /// between -1 and 1.
  ///
  /// The field is evaluated directly, so this works anywhere without
  /// generating a chunk, and changes smoothly as [position] moves. At the
  /// centre of a tile, it's the value the biome conditions saw.
  ///
  /// Throws if [field] isn't one of the generator's fields.
  double valueAt(NoiseField field, Vector2 position) {
    final tile = tileset.tileSize;
    return _queries.valueAt(
      field,
      position.x / tile.x - 0.5,
      position.y / tile.y - 0.5,
    );
  }

  /// Changes the tile at [coord] to [type].
  ///
  /// The change is recorded in [edits], so it stays when the chunk unloads
  /// and loads again. Works anywhere, even where no chunk is loaded. A loaded
  /// chunk shows the new tile, with its transitions and hitboxes, from the
  /// next [update]. Queries return it right away.
  ///
  /// Objects on the tile stay where they are.
  ///
  /// Throws if [type] isn't in the tileset or any biome.
  void setTile(TileCoord coord, TileType type) {
    if (!_palette.contains(type)) {
      throw ArgumentError.value(
        type,
        'type',
        'is not in the tileset or any biome. Add it to Tileset(tiles: ...)',
      );
    }
    final id = _palette.idOf(type);
    recordTile(edits, coord, type.name);
    _editTile(coord, id);

    final chunk = grid.chunkOf(coord);
    final loaded = _loaded[chunk];
    if (loaded == null) return;
    final index = grid.localIndex(coord);
    final previous = loaded.data.tiles[index];
    if (previous == id) return;
    loaded.data.tiles[index] = id;

    _repaint.add(chunk);
    // Hitboxes are grouped by tile type, so water to stone changes them too.
    if (_solid[previous] || _solid[id]) _rebuildSolids.add(chunk);
    // In a dual grid, the chunks right of and below this one draw its last
    // column and row.
    if (_painter.dualGrid != null) {
      final last = grid.size - 1;
      final origin = grid.origin(chunk);
      final right = coord.x - origin.x == last;
      final bottom = coord.y - origin.y == last;
      if (right) _repaint.add(chunk.translate(1, 0));
      if (bottom) _repaint.add(chunk.translate(0, 1));
      if (right && bottom) _repaint.add(chunk.translate(1, 1));
    }
  }

  void _editTile(TileCoord coord, int id) {
    (_editedTiles[grid.chunkOf(coord)] ??= {})[grid.localIndex(coord)] = id;
  }

  /// Returns the tile under [position], in the map's coordinates.
  TileCoord tileCoordAt(Vector2 position) {
    final tile = tileset.tileSize;
    return TileCoord(
      (position.x / tile.x).floor(),
      (position.y / tile.y).floor(),
    );
  }

  /// Returns the top-left corner of [coord], in the map's coordinates.
  Vector2 positionOf(TileCoord coord) {
    final tile = tileset.tileSize;
    return Vector2(coord.x * tile.x, coord.y * tile.y);
  }

  /// The chunk that holds [tile]: loaded, cached, or generated now.
  ChunkData _chunkData(TileCoord tile) {
    final coord = grid.chunkOf(tile);
    final loaded = _loaded[coord];
    if (loaded != null) return loaded.data;
    final cached = _cache.get(coord);
    if (cached != null) return cached;
    final chunk = _queries.generate(coord);
    _cache.put(chunk);
    return chunk;
  }

  /// The chunks currently loaded.
  @visibleForTesting
  Iterable<ChunkCoord> get loadedChunks => _loaded.keys;

  /// Whether every chunk the last [update] wanted is loaded. False while the
  /// worker is starting.
  @visibleForTesting
  bool get isSettled => _streamer?.inFlight == 0;

  /// The part of the tileset's atlas drawn for [tile], which must be in a
  /// loaded chunk. Only for tilesets without transitions, where each tile is
  /// one sprite.
  @visibleForTesting
  Rect sourceRectAt(TileCoord tile) {
    assert(_painter.dualGrid == null, 'tiles are drawn in a dual grid');
    return paintedChunk(
      grid.chunkOf(tile),
    )!.mesh.sourceAt(grid.localIndex(tile));
  }

  /// The sprites of the chunk at [coord], or null if it isn't loaded.
  @visibleForTesting
  PaintedChunk? paintedChunk(ChunkCoord coord) => _loaded[coord]?.painted;

  /// The size of one chunk, in pixels.
  final Vector2 _chunkPixels;

  @override
  Future<void> onLoad() async {
    _active = true;
    assert(
      !collision || findParent<HasCollisionDetection>() != null,
      'ProceduralMap(collision: true) needs HasCollisionDetection on the '
      'game or the world. Without it, the hitboxes never collide.',
    );
    _sources = tileset.sources(_palette, seed: seed);
    _painter = ChunkPainter(
      grid: grid,
      tileWidth: tileset.tileSize.x,
      tileHeight: tileset.tileSize.y,
      sources: _sources,
      dualGrid: tileset.dualGrid(_palette),
    );
    _frames = [
      for (var id = 0; id < _sources.length; id++)
        _sources.isAnimated(id) ? _sources.frameAt(id, _time) : -1,
    ];
    await _startStreaming();
  }

  @override
  void onMount() {
    _active = true;
    // The map was removed and added again.
    if (_streamer == null) unawaited(_startStreaming());
  }

  @override
  void onRemove() {
    _active = false;
    _streamer?.dispose();
    _streamer = null;
  }

  Future<void> _startStreaming() => _starting ??= () async {
    try {
      final executor = await createExecutor(
        // Scatter.spawn may capture images, which can't cross isolates.
        generator.withPlainScatterRules(),
        seed: seed,
        grid: grid,
        tiles: tileset.tiles.keys,
        frameBudget: streaming.frameBudget,
      );
      if (!_active || _streamer != null) {
        executor.dispose();
        return;
      }
      _streamer = ChunkStreamer(
        executor: executor,
        options: streaming,
        cache: _cache,
        onLoaded: _load,
        onUnloaded: _unload,
      );
    } finally {
      _starting = null;
    }
  }();

  @override
  void update(double dt) {
    _time += dt;
    _animate();
    _applyEdits();

    final streamer = _streamer;
    final visible = _activeCamera.visibleWorldRect;
    if (streamer == null || visible.isEmpty) return;
    streamer.update(_visibleChunks(visible));
  }

  @override
  void render(Canvas canvas) {
    final visible = _activeCamera.visibleWorldRect;
    for (final chunk in _loaded.values) {
      final painted = chunk.painted;
      if (painted.bounds.overlaps(visible)) {
        painted.mesh.render(canvas, tileset.atlas, _paint);
      }
    }
  }

  @override
  void renderDebugMode(Canvas canvas) {
    final border = Paint()
      ..style = PaintingStyle.stroke
      ..strokeWidth = 1
      ..color = debugColor;
    final spot = Paint()..color = debugColor;
    final tile = tileset.tileSize;
    final spotRadius = tile.x / 4;

    for (final MapEntry(key: coord, value: chunk) in _loaded.entries) {
      canvas.drawRect(chunk.bounds, border);
      debugTextPaint.render(
        canvas,
        '${coord.x}, ${coord.y}',
        Vector2(chunk.bounds.left + 4, chunk.bounds.top + 4),
      );
      for (final s in chunk.data.spots) {
        canvas.drawCircle(Offset(s.x * tile.x, s.y * tile.y), spotRadius, spot);
      }
    }
  }

  /// Shows the current frame of every animation whose frame changed.
  void _animate() {
    for (final id in _sources.animatedIds) {
      final frame = _sources.frameAt(id, _time);
      if (frame == _frames[id]) continue;
      _frames[id] = frame;
      final source = _sources.frameRect(id, frame);
      for (final chunk in _loaded.values) {
        chunk.painted.showFrame(id, source);
      }
    }
  }

  /// Repaints the chunks and rebuilds the hitboxes that [setTile] changed.
  void _applyEdits() {
    for (final coord in _repaint) {
      final chunk = _loaded[coord];
      chunk?.painted = _painter.paint(chunk.data, _tileIdAt, _time);
    }
    _repaint.clear();
    if (collision) {
      for (final coord in _rebuildSolids) {
        final chunk = _loaded[coord];
        if (chunk == null) continue;
        removeAll(chunk.solids);
        chunk.solids = _solidTiles(chunk.data);
        addAll(chunk.solids);
      }
    }
    _rebuildSolids.clear();
  }

  void _load(ChunkData data) {
    final edited = _editedTiles[data.coord];
    if (edited != null) {
      for (final MapEntry(key: index, value: id) in edited.entries) {
        data.tiles[index] = id;
      }
    }
    final tile = tileset.tileSize;
    final origin = data.origin;
    final chunk = _LoadedChunk(
      data,
      _palette,
      generator,
      tile,
      _painter.paint(data, _tileIdAt, _time),
      Rect.fromLTWH(
        origin.x * tile.x,
        origin.y * tile.y,
        _chunkPixels.x,
        _chunkPixels.y,
      ),
    );
    _loaded[data.coord] = chunk;
    if (collision) {
      chunk.solids = _solidTiles(data);
      addAll(chunk.solids);
    }
    _spawn(chunk);

    // In a dual grid, the chunks right of and below this one draw some of
    // its tiles. Until now, they used their own edge tiles in their place.
    if (_painter.dualGrid != null) {
      for (final (dx, dy) in const [(1, 0), (0, 1), (1, 1)]) {
        final neighbour = _loaded[data.coord.translate(dx, dy)];
        neighbour?.painted = _painter.paint(neighbour.data, _tileIdAt, _time);
      }
    }
    onChunkLoaded?.call(chunk);
  }

  /// The tile id at ([x], [y]), or null if its chunk isn't loaded.
  int? _tileIdAt(int x, int y) {
    final tile = TileCoord(x, y);
    final chunk = _loaded[grid.chunkOf(tile)];
    return chunk?.data.tiles[grid.localIndex(tile)];
  }

  void _unload(ChunkData data) {
    final chunk = _loaded.remove(data.coord);
    if (chunk == null) return;
    removeAll(chunk.solids);
    for (final object in chunk.objects) {
      object.removeFromParent();
    }
    onChunkUnloaded?.call(chunk);
  }

  /// Adds the components of [chunk]'s spots to the map's parent.
  void _spawn(_LoadedChunk chunk) {
    final parent = this.parent;
    assert(parent != null, 'chunks only load while the map is mounted');
    if (parent == null) return;
    for (final spot in chunk.spots) {
      final rule = spot.rule;
      if (rule is! Scatter) continue;
      final object = rule.spawn(spot);
      if (object == null) continue;
      chunk.objects.add(object);
      parent.add(object);
    }
  }

  /// The hitboxes of the solid tiles in [data], one component per tile type.
  List<SolidTiles> _solidTiles(ChunkData data) {
    final tile = tileset.tileSize;
    final origin = data.origin;
    return [
      for (final MapEntry(key: id, value: rects) in mergeTiles(
        data,
        (id) => _solid[id],
      ).entries)
        SolidTiles(
          type: _palette[id],
          chunk: data.coord,
          position: Vector2(origin.x * tile.x, origin.y * tile.y),
          size: _chunkPixels.clone(),
          rects: [
            for (final rect in rects)
              Rect.fromLTWH(
                rect.x * tile.x,
                rect.y * tile.y,
                rect.width * tile.x,
                rect.height * tile.y,
              ),
          ],
        ),
    ];
  }

  /// The chunks that [visible] overlaps.
  ChunkRange _visibleChunks(Rect visible) {
    final pixels = _chunkPixels;
    return ChunkRange(
      (visible.left / pixels.x).floor(),
      (visible.top / pixels.y).floor(),
      (visible.right / pixels.x).floor(),
      (visible.bottom / pixels.y).floor(),
    );
  }
}

class _LoadedChunk implements Chunk {
  _LoadedChunk(
    this.data,
    this._palette,
    this._generator,
    this._tileSize,
    this.painted,
    this.bounds,
  );

  final ChunkData data;
  final TilePalette _palette;
  final WorldGenerator _generator;
  final Vector2 _tileSize;

  /// The chunk's sprites. Painted again when a neighbour loads.
  PaintedChunk painted;

  /// The chunk's hitboxes, if the map has collision.
  List<SolidTiles> solids = const [];

  /// The components spawned for the chunk's spots.
  final objects = <Component>[];

  @override
  final Rect bounds;

  @override
  ChunkCoord get coord => data.coord;

  @override
  Iterable<TileCoord> get coords => data.coords;

  @override
  bool contains(TileCoord tile) => data.contains(tile);

  @override
  TileType tileAt(TileCoord tile) => _palette[data.tileIdAt(tile)];

  @override
  Biome biomeAt(TileCoord tile) => _generator.biomes[data.biomeAt(tile)];

  @override
  late final List<ScatterSpot> spots = List.unmodifiable([
    for (final spot in data.spots) _Spot(spot, this),
  ]);

  @override
  String toString() => 'Chunk($coord)';
}

class _Spot implements ScatterSpot {
  _Spot(this._data, this._chunk);

  final SpotData _data;
  final _LoadedChunk _chunk;

  @override
  ScatterRule get rule => _chunk._generator.scatterRules[_data.ruleIndex];

  @override
  Vector2 get position {
    final tile = _chunk._tileSize;
    return Vector2(_data.x * tile.x, _data.y * tile.y);
  }

  @override
  TileCoord get coord => _data.coord;

  @override
  Biome get biome => _chunk.biomeAt(coord);

  @override
  late final Random random = WorldRandom(_data.seed);

  @override
  String toString() => 'ScatterSpot(${rule.name}, $coord)';
}
